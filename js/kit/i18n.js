let current = "en";

export function setLang(lang) {
  current = STRINGS[lang] ? lang : "en";
  if (typeof document !== "undefined") {
    document.documentElement.lang = current;
    document.documentElement.dir = current === "ur" ? "rtl" : "ltr";
  }
}

export function t(key, vars) {
  let s = (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function has(key) {
  return !!(STRINGS[current] && STRINGS[current][key]);
}

export function lang() {
  return current;
}

// Game texts: the English lives in each game file; translations live here as "<game>.<field>".
export function gameText(def, field) {
  const key = `${def.id}.${field}`;
  if (has(key)) return field === "skills" ? t(key).split("|") : t(key);
  return { title: def.title, focus: def.focus, skills: def.skills, input: def.inputLabel, touch: def.touchLabel }[field];
}

export function levelText(def, index, field) {
  const key = `${def.id}.${index + 1}.${field}`;
  return has(key) ? t(key) : def.levels[index][field];
}

// How to play: [icon, text] steps. English lives in the game file (def.howTo); translations here as
// "<game>.howto.<n>".
export function howToText(def) {
  return (def.howTo || []).map(([icon, text], i) => [icon, has(`${def.id}.howto.${i + 1}`) ? t(`${def.id}.howto.${i + 1}`) : text]);
}

// Praise in a random order, without repeating the last one.
let lastPraise = 0;
export function praise() {
  let n;
  do n = 1 + Math.floor(Math.random() * 6); while (n === lastPraise);
  lastPraise = n;
  return t("praise" + n);
}

